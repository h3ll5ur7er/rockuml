/// The types of element, sorted.
pub(super) fn get_type() -> BTreeSet<String> {
    TYPES.iter().map(|&name| name.to_owned()).collect()
}

/// The keywords and every start and end directive, sorted.
pub(super) fn get_keyword() -> BTreeSet<String> {
    let directives = DIRECTIVE_PAIRS
        .iter()
        .flat_map(|name| [format!("@start{name}"), format!("@end{name}")]);
    KEYWORDS
        .iter()
        .map(|&keyword| keyword.to_owned())
        .chain(directives)
        .collect()
}
