//! The license card, `license`: rockuml's license, in the layout of PlantUML's.

use std::rc::Rc;
use std::sync::LazyLock;

use regex::Regex;

use super::{Card, UgDiagram};
use crate::diagram::builder::{PSystemSingleLineFactory, whole_line};
use crate::diagram::{Diagram, NotYetPorted, UmlSource};
use crate::klimt::TextBlock;
use crate::klimt::graphic_strings::GraphicStrings;
use crate::klimt::typeface::FontRegistry;

/// `license`, also spelled `licence`, `lisense`… (PlantUML's `PSystemLicenseFactory`).
pub(in crate::diagram) struct PSystemLicenseFactory;

impl PSystemSingleLineFactory for PSystemLicenseFactory {
    fn execute_line(
        source: &Rc<UmlSource>,
        line: &str,
    ) -> Option<Result<Box<dyn Diagram>, NotYetPorted>> {
        static PATTERN: LazyLock<Regex> = LazyLock::new(|| whole_line(r"(?i)li[sc][ea]n[sc]e\s*"));
        PATTERN
            .is_match(line)
            .then(|| Ok(UgDiagram::boxed(source, PSystemLicense)))
    }
}

/// PlantUML's `PSystemLicense`.
struct PSystemLicense;

impl Card for PSystemLicense {
    fn get_text_block(&self, _fonts: &FontRegistry) -> Box<dyn TextBlock + '_> {
        Box::new(GraphicStrings::create_black_on_white(&License::get_text()))
    }
}

/// What rockuml is distributed under (PlantUML's `License`, which says the same of PlantUML's LGPL
/// edition).
struct License;

impl License {
    fn get_text() -> Vec<String> {
        let mut text = Vec::new();
        Self::header1(&mut text);
        Self::header2(&mut text);
        Self::end3(&mut text);
        text.into_iter().map(str::to_owned).collect()
    }

    fn header1(text: &mut Vec<&str>) {
        text.extend([
            "+=======================================================================",
            "| ",
            "|      rockuml : a PlantUML-compatible diagram generator",
            "| ",
            "+=======================================================================",
        ]);
    }

    fn header2(text: &mut Vec<&str>) {
        text.extend([
            " ",
            "rockuml is a port to Rust of PlantUML, (C) Copyright 2009-2024, Arnaud Roques",
            " ",
            "Project Info:  https://github.com/h3ll5ur7er/rockuml",
            " ",
        ]);
    }

    fn end3(text: &mut Vec<&str>) {
        Self::add_lgpl(text);
        text.extend([
            " ",
            "Its layout code, ported from Graphviz by way of PlantUML's Smetana, is distributed under",
            "the Eclipse Public License, version 1.0.",
            " ",
            "Images (whatever their format : PNG, SVG...) generated by running rockuml",
            "are owned by the author of their corresponding sources code (that is, their",
            "textual description in PlantUML language). Those images are not covered by",
            "this LGPL license.",
            " ",
            "The generated images can then be used without any reference to the LGPL license.",
            "It is not even necessary to stipulate that they have been generated with rockuml.",
            " ",
            "There is an exception : if the textual description in PlantUML language is also covered",
            "by any license, then the generated images are logically covered",
            "by the very same license.",
            " ",
            "rockuml lays out every diagram itself: it needs no GraphViz installation.",
            " ",
            "Fonts Liberation Sans, Serif and Mono (c) Red Hat, Inc., under the SIL Open Font License 1.1",
            "Icons provided by OpenIconic :  https://useiconic.com/open",
            "Archimate sprites provided by Archi :  http://www.archimatetool.com",
            "Stdlib: PlantUML's standard library, each library under the license of its project",
            "Themes (c) by Brett Schwarz https://github.com/bschwarz/puml-themes and others",
            "Twemoji (c) by Twitter at https://twemoji.twitter.com/",
            " ",
        ]);
    }

    fn add_lgpl(text: &mut Vec<&str>) {
        text.extend([
            "rockuml is free software; you can redistribute it and/or modify it",
            "under the terms of the GNU Lesser General Public License as published by",
            "the Free Software Foundation, either version 3 of the License, or",
            "(at your option) any later version.",
            " ",
            "rockuml is distributed in the hope that it will be useful, but",
            "WITHOUT ANY WARRANTY; without even the implied warranty of MERCHANTABILITY",
            "or FITNESS FOR A PARTICULAR PURPOSE. See the GNU Lesser General Public",
            "License for more details.",
            " ",
            "You should have received a copy of the GNU Lesser General Public License",
            "along with this library.  If not, see <https://www.gnu.org/licenses/>.",
        ]);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rockuml_tells_its_own_licenses() {
        let text = License::get_text().join("\n");
        assert!(text.contains("rockuml is free software"));
        assert!(text.contains("GNU Lesser General Public License"));
        assert!(text.contains("Eclipse Public License, version 1.0"));
        assert!(text.contains("SIL Open Font License 1.1"));
        assert!(!text.contains("patreon"));
    }
}
